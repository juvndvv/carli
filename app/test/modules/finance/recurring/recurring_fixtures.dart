RecurringRule recurringRule({
  String id = 'netflix',
  String frequency = 'monthly',
  int interval = 1,
  int? dayOfMonth = 27,
  String startDate = '2026-01-27',
  String? nextOccurrence = '2026-10-27',
  bool isSubscription = true,
  bool cancelled = false,
  bool? active,
  Json? pending,
  String kind = 'expense',
  int amount = -1399,
}) => RecurringRule.fromJson(
  recurringRuleJson(
    id: id,
    frequency: frequency,
    interval: interval,
    dayOfMonth: dayOfMonth,
    startDate: startDate,
    nextOccurrence: nextOccurrence,
    isSubscription: isSubscription,
    cancelled: cancelled,
    active: active,
    pending: pending,
    kind: kind,
    amount: amount,
  ),
);

