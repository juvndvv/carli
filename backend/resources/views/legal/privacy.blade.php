<h1>Política de privacidad de carli</h1>
<p>Última actualización: 3 de noviembre de 2026.</p>

<h2>Quién la usa</h2>
<p>carli es una app de uso personal. El registro está cerrado: las cuentas las crea a mano su propietario y no se ofrece al público.</p>

<h2>Datos de Google</h2>
<p>Si conectas una cuenta de Google, carli pide solo el permiso de lectura de Google Calendar (<code>https://www.googleapis.com/auth/calendar.readonly</code>). Con él lee la lista de tus calendarios y los eventos de los calendarios que elijas, desde 60 días atrás hasta un año adelante, para mostrarlos en el calendario de la app y en el aviso diario.</p>
<ul>
<li>carli nunca crea, cambia ni borra nada en Google.</li>
<li>Los tokens de acceso se guardan cifrados en el servidor de carli y solo se usan para leer tu calendario.</li>
<li>Los datos no se venden, no se comparten con terceros, no se usan para publicidad ni para entrenar modelos de IA.</li>
<li>El uso de la información recibida de las API de Google cumple la <a href="https://developers.google.com/terms/api-services-user-data-policy">Google API Services User Data Policy</a>, incluidos los requisitos de uso limitado.</li>
</ul>

<h2>Cómo borrar tus datos</h2>
<p>En la app, Ajustes › Calendarios › Desconectar revoca el permiso en Google y borra al momento la cuenta y sus eventos del servidor. También puedes retirar el acceso desde <a href="https://myaccount.google.com/permissions">myaccount.google.com/permissions</a>; en ese caso carli deja de leer y puedes desconectarla para borrar la copia.</p>

<h2>Dónde se guardan</h2>
<p>En un servidor propio en la Unión Europea (AWS, Estocolmo), con copias de seguridad cifradas.</p>

<h2>Contacto</h2>
<p>Escribe al correo de asistencia que aparece en la pantalla de permisos de Google al conectar la cuenta.</p>
