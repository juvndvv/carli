export const FINANCE_ICONS = iconsFromNodes(FINANCE_ICON_NODES);

export function registerFinanceIcons(registry: IconRegistry = inject(IconRegistry)): void {
  if (!registry.has('split')) {
    registry.register(...FINANCE_ICONS);
  }
}

export function provideFinanceIcons(): EnvironmentProviders {
  return makeEnvironmentProviders([provideEnvironmentInitializer(() => registerFinanceIcons())]);
}

